const fs = require("fs");
const path = require("path");

const repoRoot = path.resolve(__dirname, "..");
const indexPath = path.join(repoRoot, "index.html");
const outputPath = path.join(repoRoot, "skills", "sfx-knowledge", "references", "site-video-memory.md");

function readRecords() {
  const html = fs.readFileSync(indexPath, "utf8");
  const match = html.match(/const records = ([\s\S]*?);\r?\n\r?\n\s*const imageManifest/);
  if (!match) throw new Error("Could not locate records in index.html");
  return JSON.parse(match[1]);
}

function list(items, indent = "") {
  return (items || []).map((item) => `${indent}- ${String(item).trim()}`).join("\n");
}

function renderRecord(record) {
  const lines = [
    `## ${record.videoId} - ${record.title}`,
    `- Source: \`${record.url}\``,
    `- Creator: ${record.source || "Unknown"}`,
    `- Added / updated: ${record.addedAt || "unknown"} / ${record.updatedAt || record.addedAt || "unknown"}`,
    `- Category: ${[record.category, ...(record.secondaryCategories || [])].filter(Boolean).join(", ")}`,
    `- Summary: ${record.summary || ""}`,
    "",
    "### Core Ideas",
    list(record.coreIdeas),
    "",
    "### Step / Event Map",
  ];

  for (const step of record.steps || []) {
    lines.push(`${step.order}. **${step.name}**: ${step.detail}`);
    if (step.params?.length) lines.push(list(step.params, "   "));
    if (step.imageKey) lines.push(`   - Evidence image key: \`${step.imageKey}\``);
    if (step.motion?.src) lines.push(`   - Motion reference: \`${step.motion.src}\``);
  }

  lines.push("", "### Plugin and Processing Notes");
  for (const plugin of record.plugins || []) {
    lines.push(`- **${plugin.name}**: ${plugin.purpose || ""}`);
    if (plugin.settings?.length) lines.push(list(plugin.settings, "  "));
  }

  lines.push("", "### Materials / Layer Sources", list(record.materials));
  lines.push("", "### Effect-Chain Reasoning", list(record.chainFocus));
  lines.push("", "### Parameter Logic", list(record.parameterLogic));
  lines.push("", "### Practice Checklist", list(record.practiceChecklist));
  lines.push("", `- Use when: ${(record.keywords || []).join("; ")}`);
  return lines.filter((line, index, all) => line !== "" || all[index - 1] !== "").join("\n");
}

const records = readRecords();
const header = [
  "# Site Video Memory",
  "",
  "> Auto-generated from `index.html` by `tools/export-site-memory.cjs`. Do not edit this file by hand.",
  "> Use it when exact per-video steps, visible parameters, plugin roles, effect-chain reasoning, or practice tasks are needed.",
  "",
  `Records: ${records.length}`,
  "",
];
const output = `${header.join("\n")}${records.map(renderRecord).join("\n\n")}\n`.replace(/[ \t]+$/gm, "");
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output, "utf8");
console.log(JSON.stringify({ outputPath, records: records.length, bytes: Buffer.byteLength(output) }, null, 2));
